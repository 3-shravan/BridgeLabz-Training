public class AvgMarksInPCM {
  public static void main(String[] args) {
    int maths = 94;
    int physics = 95;
    int chemistry = 96;

    int totalMarks = maths + physics + chemistry;
    float average = totalMarks / 3.0f;

    System.out.println("Sam’s average mark in PCM is" + average);
  }
}
